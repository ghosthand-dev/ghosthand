# Build assets/char-tracks.js from fit_*.json: per-frame [x,y,R,L,W,ang,yaw,pitch,roll,blink].
import json
import os
import numpy as np

def load(name):
    rows = json.load(open(name))
    n = len(rows)
    keys = ['yaw', 'pitch', 'roll']
    P = np.array([r['p'] if r['p'] else [np.nan]*3 for r in rows], float)
    B = np.array([r['blink'] if r['p'] else np.nan for r in rows], float)
    idx = np.arange(n)
    if name == 'fit_text1.json':
        # head turns from facing away to the front before its eyes show
        first = int(np.argmax(~np.isnan(P[:, 0])))
        for k in range(first):
            P[k] = P[first] + [0.45 * (first - k), 0, 0]
    for c in range(3):
        ok = ~np.isnan(P[:, c])
        P[:, c] = np.interp(idx, idx[ok], P[ok, c])
    ok = ~np.isnan(B)
    B = np.interp(idx, idx[ok], B[ok])
    out = []
    for k, r in enumerate(rows):
        if r['i'] >= 67 or name != 'fit_s1.json':  # headset on: body is a circle, PCA is skewed by the cups
            r['L'] = r['W'] = r['R']; r['ang'] = 0
        out.append([r['x'], r['y'], r['R'], r['L'], r['W'], r['ang'], *[round(float(v), 3) for v in P[k]], round(float(B[k]), 2)])
    return rows[0]['i'], out

tracks = {}
for key, f in [('s1', 'fit_s1.json'), ('phone', 'fit_phone.json'), ('text1', 'fit_text1.json'), ('text2', 'fit_text2.json'), ('isl', 'fit_isl.json'), ('out', 'fit_out.json')]:
    start, frames = load(f)
    tracks[key] = dict(start=start, frames=frames)
js = '// Generated by tools/gen-tracks.py from the source video. Frame = 1/30 s.\n'
js += '// Each frame: [x, y, R, L, W, ang, yaw, pitch, roll, blink] in 1280x720 px.\n'
js += 'window.MASCOT_TRACKS = ' + json.dumps(tracks, separators=(',', ':')) + ';\n'
open(os.path.join(os.path.dirname(__file__), '..', 'assets', 'data', 'mascot-tracks.js'), 'w').write(js)
print({k: (v['start'], len(v['frames'])) for k, v in tracks.items()})
